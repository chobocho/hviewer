/* 한자 유니코드 → 한글 음 (없으면 0 반환). 테이블은 코드포인트 정렬 → 이진 탐색. */
static wchar_t hanja_to_hangul(wchar_t ch) {
    /* CJK Unified Ideographs 범위만 처리 */
    if (ch < 0x4E00 || ch > 0x9FFF) return 0;
    uint16_t key = (uint16_t)ch;
    int lo = 0, hi = HANJA_TABLE_SIZE - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        uint16_t k = HANJA_TABLE[mid].hanja;
        if (k == key) return (wchar_t)HANJA_TABLE[mid].hangul;
        if (k < key) lo = mid + 1;
        else         hi = mid - 1;
    }
    return 0;
}

static inline int is_cjk(wchar_t ch) {
    return (ch >= 0x4E00 && ch <= 0x9FFF) ||  /* CJK Unified Ideographs */
           (ch >= 0x3400 && ch <= 0x4DBF) ||  /* Extension A */
           (ch >= 0xF900 && ch <= 0xFAFF);    /* CJK Compatibility Ideographs */
}

static inline int is_kana(wchar_t ch) {
    return (ch >= 0x3041 && ch <= 0x309F) ||  /* 히라가나 */
           (ch >= 0x30A0 && ch <= 0x30FF);    /* 카타카나 */
}

