#define KANA_TABLE_SIZE ((int)(sizeof(KANA_TABLE) / sizeof(KANA_TABLE[0])))

static const wchar_t *kana_to_hangul(wchar_t ch) {
    /* 카타카나 → 히라가나 오프셋: ア(0x30A2) - あ(0x3042) = 0x60 */
    if (ch >= 0x30A0 && ch <= 0x30FF) {
        ch = (wchar_t)(ch - 0x60);
    }
    uint16_t key = (uint16_t)ch;
    int lo = 0, hi = KANA_TABLE_SIZE - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        uint16_t k = KANA_TABLE[mid].kana;
        if (k == key) return KANA_TABLE[mid].hangul;
        if (k < key) lo = mid + 1;
        else         hi = mid - 1;
    }
    return NULL;
}

